async function noOverflow(label) {
  const size = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }));
  assert.ok(size.document <= size.viewport, `${label}: ${JSON.stringify(size)}`);
  check(`${label}: no document overflow at 360 px`);
}
async function scan(label) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
  a11y.push({ label, violations: result.violations });
  assert.deepEqual(result.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), [], `axe: ${label}`);
  check(`axe WCAG A/AA scan: ${label}, zero detected violations`);
}
